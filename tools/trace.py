"""Generate the requirements traceability matrix.

Requirements come from docs/safety/requirements.md.  Implementation and test
links come from the LA-REQ IDs cited in source and test files; test files are
mapped to their CTest names through the CMakeLists.txt registrations.

Usage: tools/trace.py > docs/safety/traceability.md
       tools/trace.py --check   (exit 1 if a requirement has no link)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REQ = re.compile(r"LA-REQ-\d{3}")

# Requirements exercised by the upstream ThreadX regression suite on QEMU
# (docs/safety/verification.md, "Integration tests").
REGRESSION = {"LA-REQ-%03d" % n for n in list(range(2, 10)) + [11, 12] + list(range(101, 108))}

IMPL_DIRS = ["ports/loongarch64", "bsp/qemu_virt"]
TEST_DIRS = ["test/bringup", "test/threadx_demo"]
SUFFIXES = {".c", ".h", ".S", ".inc"}


def requirements():
    rows = []
    text = (ROOT / "docs/safety/requirements.md").read_text(encoding="utf-8")
    for m in re.finditer(r"^\|\s*(LA-REQ-\d{3})\s*\|\s*(.*?)\s*\|\s*([A-Z, ]+?)\s*\|\s*$", text, re.M):
        rows.append((m.group(1), m.group(2), m.group(3)))
    return rows


def cited(dirs):
    links = {}
    for d in dirs:
        for path in sorted((ROOT / d).rglob("*")):
            if path.suffix not in SUFFIXES or not path.is_file():
                continue
            rel = path.relative_to(ROOT).as_posix()
            for rid in set(REQ.findall(path.read_text(encoding="utf-8", errors="replace"))):
                links.setdefault(rid, []).append(rel)
    return links


def ctest_names():
    """Map test source file -> CTest names."""
    names = {}
    for d in TEST_DIRS:
        cml = (ROOT / d / "CMakeLists.txt").read_text(encoding="utf-8")
        target_src = {}
        for m in re.finditer(r"la64_add_qemu_executable\((\w+)\s+([^)]*)\)", cml):
            target_src[m.group(1)] = [s for s in m.group(2).split() if s.endswith(".c")]
        for m in re.finditer(r"add_test\(\s*NAME\s+(\w+)(.*?)\)\s*$", cml, re.S | re.M):
            t = re.search(r"TARGET_FILE:(\w+)", m.group(2))
            if t:
                for src in target_src.get(t.group(1), []):
                    names.setdefault(d + "/" + src, []).append(m.group(1))
    return names


def main():
    reqs = requirements()
    impl = cited(IMPL_DIRS)
    tests = cited(TEST_DIRS)
    names = ctest_names()
    unlinked = []
    out = []
    out.append("# Requirements Traceability Matrix\n")
    out.append("| | |\n|---|---|")
    out.append("| Document ID | ESL-TXLA64-RTM |")
    out.append("| Generated by | `tools/trace.py` from `docs/safety/requirements.md` and the requirement IDs cited in sources and tests |")
    out.append("| Do not edit | Regenerate with `tools/trace.py > docs/safety/traceability.md` |\n")
    out.append("Methods: **T** test, **A** analysis, **R** review, **I** inspection.  "
               "Regression: the upstream ThreadX suite, 96 tests in each of six configurations "
               "(`docs/verification/regression.md`).  Analysis evidence for all C code is the "
               "MISRA C:2025 report (`docs/misra/reports/`); review evidence is recorded in "
               "`docs/reviews/review-log.md`.\n")
    out.append("| ID | Requirement | Method | Implemented in | Bring-up / demo tests (CTest) | Regression |")
    out.append("|---|---|---|---|---|---|")
    for rid, text, method in reqs:
        i = ", ".join("`%s`" % p for p in sorted(impl.get(rid, [])))
        tl = []
        for p in sorted(tests.get(rid, [])):
            tl.extend(names.get(p, []))
        t = ", ".join("`%s`" % n for n in sorted(set(tl)))
        r = "yes" if rid in REGRESSION else ""
        if not i or not (t or r or "T" not in method):
            unlinked.append(rid)
        out.append("| %s | %s | %s | %s | %s | %s |" % (rid, text, method, i or "**none**", t, r))
    out.append("")
    if unlinked:
        out.append("**Unlinked requirements:** " + ", ".join(unlinked) + "\n")
    else:
        out.append("Every requirement has at least one implementation link, and every requirement "
                   "verified by test (T) has at least one test link.\n")
    if "--check" in sys.argv:
        if unlinked:
            print("unlinked: " + ", ".join(unlinked), file=sys.stderr)
            return 1
        return 0
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
